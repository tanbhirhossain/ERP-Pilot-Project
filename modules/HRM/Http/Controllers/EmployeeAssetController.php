<?php

namespace Modules\HRM\Http\Controllers;

use App\Http\Controllers\Controller;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Inertia\Response;
use Modules\HRM\Models\Employee\Employee;
use Modules\HRM\Models\EmployeeAsset;
use Modules\HRM\Models\HrmAsset;
use Modules\HRM\Services\EmployeeAssetService;

/**
 * Company asset register and issue/return tracking.
 *
 * Two independent collections are rendered on one screen — the asset register
 * and the assignment history — so each gets its own paginator page key
 * (`page` and `assignments_page`) to stop them interfering in the query string.
 *
 * EmployeeAssetService enforces the invariants (an asset must be available, and
 * cannot be double-issued) and reports violations with DomainException, which
 * is converted to a field error here.
 */
class EmployeeAssetController extends Controller
{
    public function __construct(private readonly EmployeeAssetService $svc) {}

    public function index(Request $r): Response
    {
        $assets = HrmAsset::query()
            ->with(['currentAssignment.employee:id,employee_id,full_name'])
            ->latest('id');

        if ($status = $r->input('status')) {
            $assets->where('status', $status);
        }
        if ($category = $r->input('category')) {
            $assets->where('category', $category);
        }

        $assignments = EmployeeAsset::query()
            ->with(['asset:id,asset_code,name,category,unit_cost', 'employee:id,employee_id,full_name'])
            ->latest('issued_date');

        if ($state = $r->input('assignment_state')) {
            $state === 'open'
                ? $assignments->whereNull('returned_date')
                : $assignments->whereNotNull('returned_date');
        }
        if ($employeeId = $r->input('employee_id')) {
            $assignments->where('employee_id', $employeeId);
        }

        return Inertia::render('HRM::EmployeeAssets/Index', [
            'assets' => $assets->paginate(20, ['*'], 'page')->withQueryString(),
            'assignments' => $assignments->paginate(20, ['*'], 'assignments_page')->withQueryString(),
            'stats' => $this->stats(),
            'statuses' => HrmAsset::query()->distinct()->orderBy('status')->pluck('status'),
            'categories' => HrmAsset::query()->distinct()->orderBy('category')->pluck('category'),
            'filters' => $r->only(['status', 'category', 'assignment_state', 'employee_id']),
        ]);
    }

    public function storeAsset(Request $r): RedirectResponse
    {
        $data = $r->validate([
            'name' => ['required', 'string', 'max:200'],
            'category' => ['nullable', 'string', 'max:100'],
            'serial_no' => ['nullable', 'string', 'max:100'],
            'unit_cost' => ['nullable', 'numeric', 'min:0', 'max:99999999'],
            'status' => ['nullable', 'in:In Stock,Assigned,Returned,Damaged,Lost,Disposed'],
            'description' => ['nullable', 'string', 'max:1000'],
        ]);

        // asset_code is generated by the service via nextCode().
        $asset = $this->svc->createAsset($data);

        return back()->with('success', "Asset {$asset->asset_code} ({$asset->name}) added to the register.");
    }

    public function issue(Request $r): RedirectResponse
    {
        $data = $r->validate([
            'employee_id' => ['required', 'string', 'exists:employees,employee_id'],
            'asset_id' => ['required', 'integer', 'exists:hrm_assets,id'],
            'issued_date' => ['nullable', 'date', 'before_or_equal:today'],
            'expected_return_date' => ['nullable', 'date', 'after_or_equal:issued_date'],
            'issue_condition' => ['nullable', 'in:Good,Fair,Damaged'],
            'remarks' => ['nullable', 'string', 'max:1000'],
        ]);

        try {
            $assignment = $this->svc->issue($data['employee_id'], (int) $data['asset_id'], $data);
        } catch (\DomainException $e) {
            // "not available" / "already assigned" are user errors, not faults.
            return back()->withErrors(['asset_id' => $e->getMessage()])->withInput();
        }

        return back()->with('success', "{$assignment->asset->asset_code} issued to {$data['employee_id']}.");
    }

    public function returnAsset(Request $r, EmployeeAsset $employeeAsset): RedirectResponse
    {
        // Read the condition before validating: a Damaged or Lost asset is
        // recovered from salary, so the amount is mandatory in those cases and
        // optional otherwise.
        $condition = (string) $r->input('return_condition');
        $recoveryRule = in_array($condition, ['Damaged', 'Lost'], true) ? 'required' : 'nullable';

        $data = $r->validate([
            'returned_date' => ['nullable', 'date', 'after_or_equal:issued_date', 'before_or_equal:today'],
            'return_condition' => ['required', 'in:Good,Fair,Damaged,Lost'],
            'recovery_amount' => [$recoveryRule, 'numeric', 'min:0', 'max:99999999'],
            'remarks' => ['nullable', 'string', 'max:1000'],
        ]);

        try {
            $assignment = $this->svc->returnAsset($employeeAsset, $data);
        } catch (\DomainException $e) {
            return back()->withErrors(['return_condition' => $e->getMessage()])->withInput();
        }

        return back()->with('success', "{$assignment->asset->asset_code} returned — asset status now {$assignment->asset->status}.");
    }

    public function forEmployee(Request $r, Employee $employee): Response
    {
        $assignments = EmployeeAsset::query()
            ->with(['asset:id,asset_code,name,category,unit_cost'])
            ->where('employee_id', $employee->employee_id)
            ->latest('issued_date');

        if ($state = $r->input('assignment_state')) {
            $state === 'open'
                ? $assignments->whereNull('returned_date')
                : $assignments->whereNotNull('returned_date');
        }

        return Inertia::render('HRM::EmployeeAssets/Index', [
            'assets' => HrmAsset::query()->paginate(1, ['*'], 'page'),
            'assignments' => $assignments->paginate(20, ['*'], 'assignments_page')->withQueryString(),
            'stats' => $this->stats($employee->employee_id),
            'employee' => ['employee_id' => $employee->employee_id, 'full_name' => $employee->full_name],
            'filters' => $r->only(['assignment_state']),
        ]);
    }

    /**
     * Register totals, optionally scoped to one employee for the per-employee
     * view. `unreturned_value` is what the company is still owed in kind, and
     * `recovery_total` is what has been charged back to salary.
     *
     * @return array<string, int|float>
     */
    private function stats(?string $employeeId = null): array
    {
        $assignments = fn () => EmployeeAsset::query()
            ->when($employeeId, fn ($q, $id) => $q->where('employee_id', $id));

        $open = $assignments()->whereNull('returned_date');

        $unreturnedValue = $employeeId !== null
            ? $this->svc->unreturnedValue($employeeId)
            : (float) $open->with('asset:id,unit_cost')->get()
                ->sum(fn (EmployeeAsset $a) => (float) ($a->asset->unit_cost ?? 0));

        $recoveryTotal = $employeeId !== null
            ? $this->svc->recoveryTotal($employeeId)
            : (float) $assignments()->sum('recovery_amount');

        return [
            'total_assets' => $employeeId === null ? HrmAsset::count() : $assignments()->distinct('asset_id')->count('asset_id'),
            'in_stock' => $employeeId === null ? HrmAsset::where('status', 'In Stock')->count() : 0,
            'assigned' => $employeeId === null ? HrmAsset::where('status', 'Assigned')->count() : $open->count(),
            'damaged' => $employeeId === null ? HrmAsset::where('status', 'Damaged')->count() : $assignments()->where('return_condition', 'Damaged')->count(),
            'lost' => $employeeId === null ? HrmAsset::where('status', 'Lost')->count() : $assignments()->where('return_condition', 'Lost')->count(),
            'unreturned_value' => round($unreturnedValue, 2),
            'recovery_total' => round($recoveryTotal, 2),
        ];
    }
}
